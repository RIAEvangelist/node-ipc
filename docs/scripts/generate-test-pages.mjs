function escapeHTML(value){
    return String(value)
        .replaceAll('&','&amp;')
        .replaceAll('<','&lt;')
        .replaceAll('>','&gt;')
        .replaceAll('"','&quot;')
        .replaceAll("'",'&#39;');
}

function routeFile(route){
    assert.match(route,/^\/(?:[a-z0-9-]+\/)*$/u,`Unsafe route: ${route}`);
    return route === '/' ? 'index.html' : `${route.slice(1)}index.html`;
}

function groupRoute(group){
    return `/testing/${group.category.toLowerCase()}/${group.slug}/`;
}

function routesForInventory(inventory){
    const routes=[...baseRoutes,...inventory.groups.map(groupRoute)];
    assert.equal(new Set(routes).size,routes.length,'Generated routes must be unique.');
    return routes;
}

function categoryGroups(inventory,category){
    return inventory.groups.filter((group) => group.category === category);
}

function categoryCount(inventory,category){
    return categoryGroups(inventory,category).reduce((total,group) => total+group.count,0);
}

