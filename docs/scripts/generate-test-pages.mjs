function buildOutputs(inventory,homeSource=readFileSync(path.join(docs,'index.html'),'utf8')){
    const routes=routesForInventory(inventory);
    const outputs=new Map([
        ['index.html',renderHome(homeSource,inventory)],
        ['testing/index.html',renderTestingOverview(inventory)],
        ['data/test-inventory.json',`${JSON.stringify(inventory,null,2)}\n`],
        ['data/routes.json',`${JSON.stringify({schemaVersion:1,routes},null,2)}\n`],
        ['sitemap.xml',renderSitemap(routes)]
    ]);

    for(const category of categoryOrder){
        outputs.set(`testing/${category.toLowerCase()}/index.html`,renderCategoryPage(inventory,category));
    }
    for(const group of inventory.groups){
        outputs.set(routeFile(groupRoute(group)),renderGroupPage(inventory,group));
    }
    return outputs;
}

function generatedGroupFiles(){
    const files=[];
    for(const category of categoryOrder.map((entry) => entry.toLowerCase())){
        const root=path.join(docs,'testing',category);
        if(!existsSync(root)) continue;
        for(const entry of readdirSync(root,{withFileTypes:true})){
            if(!entry.isDirectory()) continue;
            const file=path.join(root,entry.name,'index.html');
            if(existsSync(file) && readFileSync(file,'utf8').startsWith(generatedMarker)) files.push(file);
        }
    }
    return files;
}

function checkOutputs(outputs){
    const errors=[];
    for(const [relative,expected] of outputs){
        const file=path.join(docs,...relative.split('/'));
        if(!existsSync(file)){
            errors.push(`${relative}: missing generated file`);
        }else if(readFileSync(file,'utf8') !== expected){
            errors.push(`${relative}: generated content is stale`);
        }
    }
    const expectedGroupFiles=new Set(
        [...outputs.keys()]
            .filter((relative) => /^testing\/(?:unit|functional|integration|regression)\/[^/]+\/index\.html$/u.test(relative))
            .map((relative) => path.join(docs,...relative.split('/')))
    );
    for(const file of generatedGroupFiles()){
        if(!expectedGroupFiles.has(file)) errors.push(`${path.relative(docs,file).replaceAll(path.sep,'/')}: orphan generated group page`);
    }
    assert.equal(errors.length,0,`Generated documentation is stale:\n- ${errors.join('\n- ')}\nRun node docs/scripts/generate-test-pages.mjs --write.`);
}

function writeOutputs(outputs){
    const expectedGroupFiles=new Set(
        [...outputs.keys()]
            .filter((relative) => /^testing\/(?:unit|functional|integration|regression)\/[^/]+\/index\.html$/u.test(relative))
            .map((relative) => path.join(docs,...relative.split('/')))
    );
    for(const file of generatedGroupFiles()){
        if(expectedGroupFiles.has(file)) continue;
        const directory=path.dirname(file);
        const entries=readdirSync(directory);
        assert.deepEqual(entries,['index.html'],`Refusing to remove non-generated content from ${directory}.`);
        unlinkSync(file);
        rmdirSync(directory);
    }
    for(const [relative,content] of outputs){
        const file=path.join(docs,...relative.split('/'));
        mkdirSync(path.dirname(file),{recursive:true});
        writeFileSync(file,content,'utf8');
    }
}

function generate({write=false}={}){
    const inventory=createInventory();
    assert.ok(inventory.total >= 140,`The correctness inventory must contain at least 140 cases; found ${inventory.total}.`);
    assert.equal(inventory.groups.length*5,inventory.total,'Every correctness group must contribute exactly five cases.');
    for(const category of categoryOrder){
        assert.ok(
            inventory.categories[category] >= inventory.minimumCategories[category],
            `${category} must contain at least ${inventory.minimumCategories[category]} cases; found ${inventory.categories[category]}.`
        );
    }
    for(const group of inventory.groups) assert.equal(group.count,5,`${group.category}/${group.name} must contain five cases.`);
    const outputs=buildOutputs(inventory);
    if(write) writeOutputs(outputs);
    checkOutputs(outputs);
    return {inventory,outputs,routes:routesForInventory(inventory)};
}

