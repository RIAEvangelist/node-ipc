function replaceGeneratedBlock(source,name,content){
    const start=`<!-- generated:${name}:start -->`;
    const end=`<!-- generated:${name}:end -->`;
    const startIndex=source.indexOf(start);
    const endIndex=source.indexOf(end);
    assert.ok(startIndex >= 0 && endIndex > startIndex,`docs/index.html is missing ${name} generation markers.`);
    return `${source.slice(0,startIndex)}${start}\n${content.trim()}\n${end}${source.slice(endIndex+end.length)}`;
}

